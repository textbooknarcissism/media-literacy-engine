package com.medialiteracy.benchmark

import com.medialiteracy.flagging.RulePackLinter
import com.medialiteracy.model.Category
import com.medialiteracy.model.FlagLevel
import java.time.LocalDate

/** The labeling codebook the fixtures follow (docs/benchmark/codebook.md). Bump it with the codebook. */
const val CODEBOOK_VERSION = 13

object Report {
    private const val MAX_LISTED = 40

    fun lintSection(lint: RulePackLinter.LintReport): String = buildString {
        appendLine("## Memorization lint")
        appendLine()
        if (lint.issues.isEmpty()) appendLine("No rule phrase or signal looks copied from a single test headline.")
        for (issue in lint.issues) {
            val label = if (issue.severity == RulePackLinter.Severity.ERROR) "**ERROR**" else "warning"
            appendLine("- $label (${issue.categoryId}): ${issue.message}")
        }
        appendLine()
    }

    fun toneSection(
        source: ExternalSource,
        tallies: Map<SplitPart, ToneTally>,
        hasWordLabels: Boolean,
        byGroup: Map<String, Map<SplitPart, ToneTally>> = emptyMap(),
    ): String = buildString {
        appendLine("## ${source.id}")
        appendLine()
        appendLine("${source.citation}. Year ${source.year}, license ${source.licence}.")
        appendLine()
        appendLine("**Proxy: news sentences, not headlines.** A sentence counts as toned by the engine when a visible flag includes Alarmist framing, Conflict framing or Opinion as fact.")
        appendLine()
        val tune = tallies.getValue(SplitPart.TUNE)
        val held = tallies.getValue(SplitPart.HELDOUT)
        appendLine("| | Tuning | Held-out |")
        appendLine("| :--- | :--- | :--- |")
        appendLine("| Precision on toned sentences | ${tune.precision.format()} | ${held.precision.format()} |")
        appendLine("| Recall on toned sentences | ${tune.recall.format()} | ${held.recall.format()} |")
        if (hasWordLabels) {
            appendLine("| Expert-marked words the engine underlined | ${tune.wordRecall.format()} | ${held.wordRecall.format()} |")
            appendLine("| Engine underlines landing on an expert-marked word | ${tune.hitPrecision.format()} | ${held.hitPrecision.format()} |")
        }
        appendLine()
        if (byGroup.isNotEmpty()) {
            appendLine("**By the dataset's own outlet-lean label** (research for the lean symmetry audit; MLE never knows an outlet's lean)")
            appendLine()
            appendLine("| Lean | Toned sentences flagged, tuning | Toned sentences flagged, held-out | Neutral sentences flagged, tuning | Neutral sentences flagged, held-out |")
            appendLine("| :--- | :--- | :--- | :--- | :--- |")
            for ((group, t) in byGroup) {
                val gt = t.getValue(SplitPart.TUNE)
                val gh = t.getValue(SplitPart.HELDOUT)
                appendLine("| $group | ${gt.recall.format()} | ${gh.recall.format()} | ${Rate(gt.fp, gt.fp + gt.tn).format()} | ${Rate(gh.fp, gh.fp + gh.tn).format()} |")
            }
            appendLine()
        }
    }

    fun teaseSection(source: ExternalSource, tallies: Map<SplitPart, TeaseTally>): String = buildString {
        appendLine("## ${source.id}")
        appendLine()
        appendLine("${source.citation}. Year ${source.year}, license ${source.licence}.")
        appendLine()
        appendLine("Every post in this corpus is clickbait, so only catching is measurable. The article's own description stands in for the RSS summary.")
        appendLine()
        val tune = tallies.getValue(SplitPart.TUNE)
        val held = tallies.getValue(SplitPart.HELDOUT)
        fun row(label: String, f: (TeaseTally) -> Rate) = appendLine("| $label | ${f(tune).format()} | ${f(held).format()} |")
        appendLine("| | Tuning | Held-out |")
        appendLine("| :--- | :--- | :--- |")
        row("Clickbait posts flagged at all") { Rate(it.flagged, it.total) }
        row("Flagged as Withheld detail") { Rate(it.flaggedCuriosity, it.total) }
        row("Answer found, where the description holds it") { Rate(it.resolvedCorrect, it.answerable) }
        row("Attached context that is not the answer") { Rate(it.resolvedWrong, it.resolved) }
        appendLine()
    }


    fun header(rulePackVersion: Int): String = """
        |# Benchmark results
        |
        |Generated by `./gradlew :tools:benchmark:run` on ${LocalDate.now()} against rule pack version $rulePackVersion and codebook version $CODEBOOK_VERSION.
        |Do not edit by hand: every number here comes from that run.
        |
        |Each dataset is split by a stable hash of its case ids: 70% tuning, 30% held-out. Held-out results are totals only, so individual held-out headlines never appear here and cannot be tuned against.
        |`harvested` and `starter` were used to tune the rules before this split existed, so their held-out numbers are optimistic. Datasets older than 2021 are regression checks, not evidence.
        |
        |Brackets after a headline rate are its 95% Wilson interval: where the true rate plausibly lies, given how many headlines were counted. Two runs whose intervals overlap widely have not been shown to differ.
        |""".trimMargin()

    /** The latest monthly flag review, MLE's main measure (docs/teaching-reset-2026-10.md §6). */
    fun flagReviewSection(r: FlagReview.Result): String = buildString {
        appendLine("## Flag review")
        appendLine()
        appendLine("The maintainer's review of ${r.sampled} headlines MLE flagged in ${r.month} (codebook version ${r.codebook}, rule pack ${r.rulePack}); " +
            "details in ${FlagReview.ROOT}/${r.month}/report.md. Target: at least ${Targets.percent(FlagReview.TARGET)} yes on each question.")
        appendLine()
        appendLine("| Question | Yes | Verdict |")
        appendLine("| :--- | :--- | :--- |")
        appendLine("| Is this a clear case? | ${r.clear.formatWithInterval()} | ${Targets.Result("", FlagReview.TARGET, r.clear).verdict.text} |")
        appendLine("| Would the highlight and question help a reader stop and think? | ${r.helps.formatWithInterval()} | ${Targets.Result("", FlagReview.TARGET, r.helps).verdict.text} |")
        appendLine()
    }

    fun targetsSection(results: List<Targets.Result>, caught: Rate): String = buildString {
        appendLine("## Left alone")
        appendLine()
        appendLine("MLE is a teaching tool: when it speaks it should be right, so the targets are on honest headlines left alone " +
            "(docs/teaching-reset-2026-10.md §6). " +
            "Pooled means the held-out rows of every evidence set: not legacy, not tuning-only, not sealed. " +
            "\"Within noise\" means the target lies inside the 95% interval, so a few headlines either way would change the verdict.")
        appendLine()
        appendLine("| Target | Measured | Verdict |")
        appendLine("| :--- | :--- | :--- |")
        for (t in results) {
            val note = if (t.note.isEmpty()) "" else " (${t.note})"
            appendLine("| ${t.target} at least ${Targets.percent(t.goal)}$note | ${t.measured.formatWithInterval()} | ${t.verdict.text} |")
        }
        appendLine()
        appendLine("## Caught (information, not a goal)")
        appendLine()
        appendLine("Pooled held-out clickbait the engine flagged: ${caught.formatWithInterval()}. " +
            "A missed headline costs a reader little, so this is published for honesty and no decision is taken to raise it.")
        appendLine()
    }

    /** A sealed set shows only that it exists: no rate, not even a total of how many are clickbait. */
    fun sealedSection(ds: HeadlineDataset, rows: Int): String = buildString {
        appendLine("## ${ds.id}")
        appendLine()
        appendLine("${ds.source}. Year ${ds.year}, license ${ds.licence}.")
        appendLine()
        appendLine("**Sealed until ${ds.sealedUntil}.** $rows rows, not scored, not gated, never listed. " +
            "Its first score after that day is the honest test of whatever rule pack is current then.")
        appendLine()
    }

    fun headlineSection(r: HeadlineReport): String = buildString {
        val ds = r.dataset
        appendLine("## ${ds.id}")
        appendLine()
        appendLine("${ds.source}. Year ${ds.year}, license ${ds.licence}.${if (ds.legacyEvidence) " **Legacy regression check, not evidence.**" else ""}")
        appendLine()
        ds.sealedUntil?.let {
            appendLine("**Unsealed on $it.** The whole set is held-out. Its first score after that day is the honest test; record it in docs/positions.md, because every later look is less independent.")
            appendLine()
        }
        r.techniques(SplitPart.HELDOUT)?.let { t ->
            appendLine("**Held-out per technique** (precision: when MLE names this technique, how often it is right)")
            appendLine()
            appendLine("| Technique | Precision | Recall |")
            appendLine("| :--- | :--- | :--- |")
            for (c in Category.entries) appendLine("| ${c.displayName} | ${t.precision(c).formatWithInterval()} | ${t.recall(c).formatWithInterval()} |")
            appendLine()
        }

        val tune = r.levels(SplitPart.TUNE)
        val held = r.levels(SplitPart.HELDOUT)
        appendLine("| | Tuning | Held-out |")
        appendLine("| :--- | :--- | :--- |")
        appendLine("| Left alone correctly | ${tune.leftAlone.formatWithInterval()} | ${held.leftAlone.formatWithInterval()} |")
        appendLine("| Caught when it should (information) | ${tune.caught.formatWithInterval()} | ${held.caught.formatWithInterval()} |")
        appendLine()

        val heldOut = r.scored.filter { it.part == SplitPart.HELDOUT }
        breakdown(this, "Held-out by article type (publisher-tagged)", heldOut.filter { it.case.typeSource == "publisher-tag" }) { it.articleType }
        breakdown(this, "Held-out by article type (section feed, noisier)", heldOut.filter { it.case.typeSource == "section-feed" }) { it.articleType }
        breakdown(this, "Held-out by article type (context declared)", heldOut.filter { it.case.typeSource !in setOf("publisher-tag", "section-feed") && it.case.articleType != null }) { it.articleType }
        breakdown(this, "Held-out by beat", heldOut) { it.beat }
        breakdown(this, "Held-out by outlet", heldOut) { it.outlet }

        val tuning = r.scored.filter { it.part == SplitPart.TUNE }
        listCases(this, "Tuning: wrongly flagged", tuning.filter { it.case.expectedLevel == FlagLevel.NONE && it.got.isFlagged })
        listCases(this, "Tuning: missed", tuning.filter { it.case.expectedLevel != FlagLevel.NONE && !it.got.isFlagged })
    }

    private fun breakdown(sb: StringBuilder, title: String, scored: List<Scored>, key: (HeadlineCase) -> String?) {
        val groups = scored.groupBy { key(it.case) }.filterKeys { it != null }
        if (groups.isEmpty()) return
        sb.appendLine("**$title**")
        sb.appendLine()
        sb.appendLine("| Group | Left alone correctly | Caught when it should |")
        sb.appendLine("| :--- | :--- | :--- |")
        for ((group, items) in groups.entries.sortedByDescending { it.value.size }) {
            val tally = LevelTally().also { t -> items.forEach { t.add(it.case.expectedLevel, it.got.level) } }
            sb.appendLine("| $group | ${tally.leftAlone.formatWithInterval()} | ${tally.caught.formatWithInterval()} |")
        }
        sb.appendLine()
    }

    private fun listCases(sb: StringBuilder, title: String, items: List<Scored>) {
        if (items.isEmpty()) return
        val shown = if (items.size > MAX_LISTED) ", first $MAX_LISTED shown" else ""
        sb.appendLine("**$title** (${items.size}$shown)")
        sb.appendLine()
        for (s in items.take(MAX_LISTED)) {
            val hits = s.got.hits.joinToString { "${it.category.displayName} -> \"${it.matchedText}\"" }
            sb.appendLine("- want ${s.case.expectedLevel}, got ${s.got.level}: ${s.case.headline}${if (hits.isNotEmpty()) " _($hits)_" else ""}")
        }
        sb.appendLine()
    }
}
