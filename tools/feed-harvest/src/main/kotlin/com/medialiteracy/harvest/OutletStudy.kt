/**
 * Research on outlets, beats and political lean, run offline over the labeled
 * headline sets and the live intake.
 *
 * Run it with:  ./gradlew :tools:feed-harvest:runOutletStudy --args="--report=build/outlet-study-results.md"
 *
 * Three questions, all descriptive. None of the numbers is an input to any
 * verdict: nothing in the app knows an outlet or its politics (decision 6,
 * codebook rule 6).
 *
 * 1. **House styles.** How often each outlet, beat and lean group uses each
 *    technique, by the labels and by the engine.
 * 2. **Lean symmetry.** Within one register (tabloid against tabloid, magazine
 *    against magazine), does the engine treat left- and right-leaning outlets
 *    alike, given what the labels say? A gap is a reason to read the headlines,
 *    not to change a weight.
 * 3. **Publisher priors.** If each outlet's labeled rate nudged the engine's
 *    score, what would that fix and what would it break on held-out headlines?
 *    The project decided not to use priors. This measures the decision so it
 *    can be revisited with numbers.
 *
 * Held-out rows appear only in totals, exactly as in the benchmark.
 */
fun main(args: Array<String>) {
    val reportPath = args.firstOrNull { it.startsWith("--report=") }?.substringAfter("--report=")
    val flagger = HeadlineFlagger(RulePackLoader.loadDefault())
    val cases = loadStudyCases(flagger)
    val kindOf = PANEL.associate { it.name to it.kind }
    checkPairs(kindOf)

    val out = StringBuilder()
    out.appendLine("# Outlet study results")
    out.appendLine()
    out.appendLine("Generated by `./gradlew :tools:feed-harvest:runOutletStudy` against rule pack ${RulePackLoader.loadDefault().version}. Do not edit by hand.")
    out.appendLine()
    val labelled = cases.filter { it.wantFlag != null }
    out.appendLine("Labeled rows: ${labelled.size} (${labelled.count { it.heldOut }} held out). Intake rows not in any labeled set: ${cases.count { it.wantFlag == null }}; their labels are the detector's own guesses, so only the engine's verdicts are used for them.")
    out.appendLine()
    houseStyles(out, cases, kindOf)
    leanSymmetry(out, cases)
    priorsExperiment(out, labelled)

    print(out)
    reportPath?.let { File(it).apply { parentFile?.mkdirs() }.writeText(out.toString(), Charsets.UTF_8) }
}

private class StudyCase(
    val dataset: String,
    val headline: String,
    val outlet: String,
    val beat: String?,
    /** Null for intake rows: their label column is the detector's own guess. */
    val wantFlag: Boolean?,
    /** Null where the dataset labels strength only. */
    val wantTechniques: Set<Category>?,
    val heldOut: Boolean,
    val result: FlagResult,
)

/** Outlets compared like with like. Each name must carry the matching lean in [PANEL]. */
internal class RegisterPair(val name: String, val left: List<String>, val right: List<String>)

internal val REGISTER_PAIRS = listOf(
    RegisterPair("UK tabloids", listOf("Daily Mirror", "Daily Star"), listOf("Daily Mail", "Daily Express")),
    RegisterPair("UK political magazines", listOf("New Statesman"), listOf("The Critic")),
    RegisterPair("US partisan online", listOf("Mother Jones"), listOf("Breitbart")),
)

private fun checkPairs(kindOf: Map<String, String>) {
    for (pair in REGISTER_PAIRS) {
        for (o in pair.left) require(kindOf[o]?.endsWith("-left") == true) { "$o is not tagged left in PANEL" }
        for (o in pair.right) require(kindOf[o]?.endsWith("-right") == true) { "$o is not tagged right in PANEL" }
    }
}

private fun sha256(text: String): String =
    MessageDigest.getInstance("SHA-256").digest(text.toByteArray(Charsets.UTF_8)).joinToString("") { "%02x".format(it) }

/** The benchmark's split (tools/benchmark Split.of): 30% of case ids, by hash, are held out. */
private fun isHeldOut(caseId: String) = sha256(caseId).substring(0, 8).toLong(16) % 100 < 30

private fun rows(path: String): List<List<String>> =
    File(path).takeIf { it.exists() }?.readLines(Charsets.UTF_8).orEmpty()
        .map { it.removePrefix("\uFEFF") }
        .filter { it.isNotBlank() && !it.trimStart().startsWith("#") }
        .map { it.split('\t') }

private fun techniques(field: String): Set<Category> =
    if (field.trim() == "-") emptySet() else field.split(',').mapNotNull { Category.fromId(it.trim()) }.toSet()

private fun loadStudyCases(flagger: HeadlineFlagger): List<StudyCase> {
    // Scored exactly as the benchmark scores them: with the article type, and the summary where there is one.
    fun flag(headline: String, type: String?, summary: String? = null): FlagResult {
        val articleType = ArticleType.fromId(type?.trim()?.takeIf { it != "unknown" })
        return if (summary.isNullOrBlank()) flagger.flag(headline, articleType = articleType)
        else flagger.flagWithSummary(headline, summary, articleType = articleType)
    }
    fun source(p: List<String>) = p.getOrNull(2)?.trim()?.removePrefix("#")?.trim().orEmpty()

    val cases = mutableListOf<StudyCase>()
    for (p in rows("fixtures/headlines/harvested.tsv")) {
        if (p.any { it.trim() == "REVIEW" }) continue
        val headline = p.getOrNull(1)?.trim()?.takeIf { it.isNotEmpty() } ?: continue
        cases += StudyCase(
            "harvested", headline, source(p), null, p[0].trim() != "NONE", null,
            isHeldOut(sha256(headline.lowercase())), flag(headline, p.getOrNull(3)),
        )
    }
    for (p in rows("fixtures/headlines/broadsheet-2026.tsv")) {
        if (p.size < 9) continue
        val headline = p[7].trim()
        cases += StudyCase(
            "broadsheet-2026", headline, p[3].trim(), null, p[0].trim() != "NONE", techniques(p[1]),
            isHeldOut(p[2].trim()), flag(headline, p[4], p[8].trim()),
        )
    }
    for (p in rows("fixtures/headlines/beats-2026.tsv")) {
        if (p.size < 11) continue
        val headline = p[10].trim()
        cases += StudyCase(
            "beats-2026", headline, p[4].trim(), p[3].trim(), p[0].trim() != "NONE", techniques(p[1]),
            isHeldOut(p[2].trim()), flag(headline, p[5]),
        )
    }
    val labelled = cases.map { it.headline.lowercase() }.toSet()
    for (p in rows("fixtures/headlines/harvested-live-intake.tsv")) {
        val headline = p.getOrNull(1)?.trim()?.takeIf { it.isNotEmpty() } ?: continue
        if (headline.lowercase() in labelled) continue
        cases += StudyCase("intake", headline, source(p), null, null, null, heldOut = false, result = flag(headline, null))
    }
    return cases
}

private fun pct(n: Int, d: Int) = if (d == 0) "n/a" else "%d/%d (%.1f%%)".format(n, d, 100.0 * n / d)
private fun rate(n: Int, d: Int) = if (d == 0) 0.0 else 100.0 * n / d

/** The technique that turns up most often in [sets], or "-". */
private fun commonest(sets: List<Set<Category>>): String =
    sets.flatten().groupingBy { it }.eachCount().maxByOrNull { it.value }?.let { "${it.key.id} (${it.value})" } ?: "-"

private fun houseStyles(out: StringBuilder, cases: List<StudyCase>, kindOf: Map<String, String>) {
    out.appendLine("## 1. House styles")
    out.appendLine()
    out.appendLine("All labeled rows, tuning and held-out together; the intake columns use the engine only. Descriptive, never a scoring input.")
    out.appendLine()
    out.appendLine("**By lean group** (the harvester's source tags; outlets outside the panel are grouped as such)")
    out.appendLine()
    out.appendLine("| Group | Labeled rows | Labeled flagged | Engine flagged | Intake rows | Engine flagged on intake |")
    out.appendLine("| :--- | :--- | :--- | :--- | :--- | :--- |")
    val group = { c: StudyCase -> kindOf[c.outlet] ?: "not in panel" }
    for ((g, xs) in cases.groupBy(group).entries.sortedBy { it.key }) {
        val lab = xs.filter { it.wantFlag != null }
        val intake = xs.filter { it.wantFlag == null }
        out.appendLine(
            "| $g | ${lab.size} | ${pct(lab.count { it.wantFlag == true }, lab.size)} | ${pct(lab.count { it.result.isFlagged }, lab.size)} | " +
                "${intake.size} | ${pct(intake.count { it.result.isFlagged }, intake.size)} |",
        )
    }
    out.appendLine()

    out.appendLine("**By outlet** (outlets with at least 20 labeled rows)")
    out.appendLine()
    out.appendLine("| Outlet | Group | Labeled rows | Labeled flagged | Engine flagged | Engine flags a clean row | Engine catches a flagged row | Commonest labeled technique | Commonest engine technique |")
    out.appendLine("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
    val byOutlet = cases.filter { it.wantFlag != null }.groupBy { it.outlet }.filter { it.value.size >= 20 }
    for ((outlet, xs) in byOutlet.entries.sortedByDescending { it.value.size }) {
        val clean = xs.filter { it.wantFlag == false }
        val flagged = xs.filter { it.wantFlag == true }
        out.appendLine(
            "| $outlet | ${kindOf[outlet] ?: "not in panel"} | ${xs.size} | ${pct(flagged.size, xs.size)} | ${pct(xs.count { it.result.isFlagged }, xs.size)} | " +
                "${pct(clean.count { it.result.isFlagged }, clean.size)} | ${pct(flagged.count { it.result.isFlagged }, flagged.size)} | " +
                "${commonest(xs.mapNotNull { it.wantTechniques })} | ${commonest(xs.map { it.result.categories.toSet() })} |",
        )
    }
    out.appendLine()

    val beats = cases.filter { it.beat != null }
    if (beats.isNotEmpty()) {
        out.appendLine("**By beat** (beats-2026): headlines carrying each technique, by the labels / by the engine")
        out.appendLine()
        val names = beats.map { it.beat!! }.distinct()
        out.appendLine("| Technique | ${names.joinToString(" | ")} |")
        out.appendLine("| :--- |${names.joinToString("") { " :--- |" }}")
        for (c in Category.entries) {
            val cells = names.map { b ->
                val xs = beats.filter { it.beat == b }
                "${xs.count { c in it.wantTechniques.orEmpty() }} / ${xs.count { c in it.result.categories }}"
            }
            out.appendLine("| ${c.id} | ${cells.joinToString(" | ")} |")
        }
        out.appendLine()
    }
}

private fun leanSymmetry(out: StringBuilder, cases: List<StudyCase>) {
    out.appendLine("## 2. Lean symmetry, like against like")
    out.appendLine()
    out.appendLine("\"Excess gap\" is how far the engine's left-right gap in flagged rate exceeds the gap the labels show. Near zero means the engine follows the labels on both sides; a large value is a reason to read the headlines behind it.")
    out.appendLine()
    out.appendLine("| Register | Side | Outlets | Labeled rows | Labeled flagged | Engine flagged | Engine flags a clean row | Engine catches a flagged row | Intake: engine flagged |")
    out.appendLine("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
    val gaps = mutableListOf<String>()
    for (pair in REGISTER_PAIRS) {
        val stats = listOf("left" to pair.left, "right" to pair.right).map { (side, outlets) ->
            val xs = cases.filter { it.outlet in outlets }
            val lab = xs.filter { it.wantFlag != null }
            val clean = lab.filter { it.wantFlag == false }
            val flagged = lab.filter { it.wantFlag == true }
            val intake = xs.filter { it.wantFlag == null }
            out.appendLine(
                "| ${pair.name} | $side | ${outlets.joinToString(", ")} | ${lab.size} | ${pct(flagged.size, lab.size)} | ${pct(lab.count { it.result.isFlagged }, lab.size)} | " +
                    "${pct(clean.count { it.result.isFlagged }, clean.size)} | ${pct(flagged.count { it.result.isFlagged }, flagged.size)} | ${pct(intake.count { it.result.isFlagged }, intake.size)} |",
            )
            Triple(rate(flagged.size, lab.size), rate(lab.count { it.result.isFlagged }, lab.size), lab.size)
        }
        val labelGap = stats[0].first - stats[1].first
        val engineGap = stats[0].second - stats[1].second
        gaps += "- ${pair.name}: labels left minus right %+.1f points, engine %+.1f points, excess gap %+.1f points (%d and %d labeled rows).".format(labelGap, engineGap, engineGap - labelGap, stats[0].third, stats[1].third)
    }
    out.appendLine()
    gaps.forEach { out.appendLine(it) }
    out.appendLine()

    out.appendLine("**Technique mix when the engine flags** (labeled and intake rows): share of flagged headlines carrying each technique")
    out.appendLine()
    out.appendLine("| Register | Side | Flagged | ${Category.entries.joinToString(" | ") { it.id }} |")
    out.appendLine("| :--- | :--- | :--- |${Category.entries.joinToString("") { " :--- |" }}")
    for (pair in REGISTER_PAIRS) {
        for ((side, outlets) in listOf("left" to pair.left, "right" to pair.right)) {
            val flagged = cases.filter { it.outlet in outlets && it.result.isFlagged }
            val cells = Category.entries.map { c -> if (flagged.isEmpty()) "n/a" else "%.0f%%".format(rate(flagged.count { c in it.result.categories }, flagged.size)) }
            out.appendLine("| ${pair.name} | $side | ${flagged.size} | ${cells.joinToString(" | ")} |")
        }
    }
    out.appendLine()

    out.appendLine("**Rules that fire on one side only** (all registers pooled, labeled and intake rows; rules with at least 3 hits, at least 80% on one side)")
    out.appendLine()
    out.appendLine("| Rule | Left hits | Right hits | Left rows | Right rows |")
    out.appendLine("| :--- | :--- | :--- | :--- | :--- |")
    val left = cases.filter { c -> REGISTER_PAIRS.any { c.outlet in it.left } }
    val right = cases.filter { c -> REGISTER_PAIRS.any { c.outlet in it.right } }
    fun ruleCounts(xs: List<StudyCase>) = xs.flatMap { c -> c.result.hits.mapNotNull { it.ruleId }.distinct() }.groupingBy { it }.eachCount()
    val l = ruleCounts(left)
    val r = ruleCounts(right)
    val skewed = (l.keys + r.keys).map { id -> Triple(id, l[id] ?: 0, r[id] ?: 0) }
        .filter { (_, a, b) -> a + b >= 3 && maxOf(a, b) >= 0.8 * (a + b) }
        .sortedByDescending { (_, a, b) -> a + b }
    for ((id, a, b) in skewed) out.appendLine("| `$id` | $a | $b | ${left.size} | ${right.size} |")
    out.appendLine()
    out.appendLine("Left rows: ${left.size}. Right rows: ${right.size}. A rule on one side only can be a difference in how the outlets write, or a word list that learned one side's vocabulary; only reading the headlines tells which.")
    out.appendLine()
}

private fun logit(p: Double) = ln(p / (1 - p))

/**
 * A publisher prior as an outside review proposed it: each outlet's own rate
 * nudges the engine's score up or down. Fitted on tuning rows, measured on
 * held-out rows. [fromEngine] fits the offsets from the engine's own flags
 * instead of the labels, which is what an app without labels would have to do.
 */
private fun priorsExperiment(out: StringBuilder, labelled: List<StudyCase>) {
    out.appendLine("## 3. Publisher priors (research only, never shipped)")
    out.appendLine()
    out.appendLine("Each outlet's flagged rate on tuning rows, pulled towards the overall rate by 20 pseudo-rows, gives an offset: the difference in log-odds between the outlet and the whole set. A headline is flagged when the engine's score plus β times the offset reaches the subtle threshold (0.5). β is chosen on tuning rows by balanced accuracy, the mean of the share of flagged rows caught and the share of clean rows left alone. \"Evidence only\" applies the offset only when the engine found something (score above 0), so a prior can never flag a headline on the outlet's name alone.")
    out.appendLine()
    val tune = labelled.filter { !it.heldOut }
    val held = labelled.filter { it.heldOut }
    val smoothing = 20.0
    fun offsets(want: (StudyCase) -> Boolean): Map<String, Double> {
        val base = tune.count(want).toDouble() / tune.size
        return tune.groupBy { it.outlet }.mapValues { (_, xs) ->
            val p = (xs.count(want) + smoothing * base) / (xs.size + smoothing)
            logit(p) - logit(base)
        }
    }
    val fromLabels = offsets { it.wantFlag == true }
    val fromEngine = offsets { it.result.isFlagged }

    fun decide(c: StudyCase, offsets: Map<String, Double>, beta: Double, evidenceOnly: Boolean): Boolean {
        val score = c.result.score
        val shift = if (evidenceOnly && score <= 0.0) 0.0 else beta * (offsets[c.outlet] ?: 0.0)
        return score + shift >= 0.5
    }
    fun balanced(xs: List<StudyCase>, flagged: (StudyCase) -> Boolean): Double {
        val pos = xs.filter { it.wantFlag == true }
        val neg = xs.filter { it.wantFlag == false }
        return (pos.count(flagged).toDouble() / pos.size + neg.count { !flagged(it) }.toDouble() / neg.size) / 2
    }
    val betas = listOf(0.0, 0.05, 0.1, 0.15, 0.2, 0.3, 0.5, 0.75, 1.0)

    val heldClean = held.filter { it.wantFlag == false }
    val heldFlagged = held.filter { it.wantFlag == true }
    val forced = listOf(0.25, 0.5, 1.0)
    out.appendLine("The first row of each prior is the β that scores best on tuning rows; the rest force a prior of growing strength, to show what it would do if adopted anyway.")
    out.appendLine()
    out.appendLine("| Offsets fitted from | Applied | β | Tuning balanced accuracy | Held-out: left alone | Held-out: caught | Misses fixed | False flags added | Catches lost | False flags removed |")
    out.appendLine("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
    out.appendLine(
        "| (no prior) | | 0 | %.3f | %s | %s | | | | |".format(
            balanced(tune) { it.result.isFlagged },
            pct(heldClean.count { !it.result.isFlagged }, heldClean.size), pct(heldFlagged.count { it.result.isFlagged }, heldFlagged.size),
        ),
    )
    val gapRows = mutableListOf<String>()
    for ((source, offs) in listOf("labels" to fromLabels, "engine flags" to fromEngine)) {
        for (evidenceOnly in listOf(false, true)) {
            val applied = if (evidenceOnly) "evidence only" else "always"
            val best = betas.maxByOrNull { b -> balanced(tune) { decide(it, offs, b, evidenceOnly) } }!!
            for (beta in (listOf(best) + forced).distinct()) {
                val f = { c: StudyCase -> decide(c, offs, beta, evidenceOnly) }
                out.appendLine(
                    "| $source | $applied | $beta${if (beta == best) " (best)" else ""} | %.3f | %s | %s | %d | %d | %d | %d |".format(
                        balanced(tune, f),
                        pct(heldClean.count { !f(it) }, heldClean.size), pct(heldFlagged.count(f), heldFlagged.size),
                        heldFlagged.count { !it.result.isFlagged && f(it) }, heldClean.count { !it.result.isFlagged && f(it) },
                        heldFlagged.count { it.result.isFlagged && !f(it) }, heldClean.count { it.result.isFlagged && !f(it) },
                    ),
                )
                if (beta != 0.5) continue
                for (pair in REGISTER_PAIRS) {
                    val l = held.filter { it.outlet in pair.left }
                    val r = held.filter { it.outlet in pair.right }
                    if (l.isEmpty() || r.isEmpty()) continue
                    val labelGap = rate(l.count { it.wantFlag == true }, l.size) - rate(r.count { it.wantFlag == true }, r.size)
                    val before = rate(l.count { it.result.isFlagged }, l.size) - rate(r.count { it.result.isFlagged }, r.size)
                    val after = rate(l.count(f), l.size) - rate(r.count(f), r.size)
                    gapRows += "| $source, $applied | ${pair.name} | ${l.size} / ${r.size} | %+.1f | %+.1f | %+.1f |".format(labelGap, before - labelGap, after - labelGap)
                }
            }
        }
    }
    out.appendLine()
    out.appendLine("**Left-right gap on held-out rows with a forced prior (β = 0.5)**, as excess over the labels' own gap (points; the rows column is left / right)")
    out.appendLine()
    out.appendLine("| Prior | Register | Rows | Labels' gap | Excess gap without prior | Excess gap with prior |")
    out.appendLine("| :--- | :--- | :--- | :--- | :--- | :--- |")
    gapRows.forEach { out.appendLine(it) }
    out.appendLine()

    // Circularity: do offsets fitted from the engine's own flags track the ones fitted from labels?
    val outlets = tune.groupBy { it.outlet }.filter { it.value.size >= 20 }.keys.toList()
    val a = outlets.map { fromLabels.getValue(it) }
    val b = outlets.map { fromEngine.getValue(it) }
    val ma = a.average()
    val mb = b.average()
    val cov = a.indices.sumOf { (a[it] - ma) * (b[it] - mb) }
    val r = cov / sqrt(a.sumOf { (it - ma) * (it - ma) } * b.sumOf { (it - mb) * (it - mb) })
    out.appendLine("**Circularity check.** Across the ${outlets.size} outlets with at least 20 tuning rows, offsets fitted from the engine's flags correlate with offsets fitted from the labels at r = %.2f. A high value means an app fitting priors from its own flags would mostly amplify what the engine already does; in harvested.tsv, whose labels began as the detector's guesses, it can also mean the labels lean on the engine.".format(r))
    out.appendLine()
    out.appendLine("| Outlet | Tuning rows | Offset from labels | Offset from engine flags |")
    out.appendLine("| :--- | :--- | :--- | :--- |")
    for (o in outlets.sortedByDescending { fromLabels.getValue(it) }) {
        out.appendLine("| $o | ${tune.count { it.outlet == o }} | %+.2f | %+.2f |".format(fromLabels.getValue(o), fromEngine.getValue(o)))
    }
    out.appendLine()
}
